"""Generate reversible presentation filters; original image pixels are unchanged."""
import json
from pathlib import Path
from PIL import Image, ImageStat

ROOT=Path(__file__).resolve().parents[1]

def grade_for(image):
    sample=image.convert('RGB').resize((96,96),Image.Resampling.BOX)
    luminance=ImageStat.Stat(sample.convert('L')).mean[0]
    saturation=ImageStat.Stat(sample.convert('HSV')).mean[1]/255
    exposure=round(max(.94,min(1.20,1+(135-luminance)*.0026)),3)
    color=round(max(.65,min(.86,.86-saturation*.42)),3)
    return dict(exposure=exposure,saturation=color,mean_luminance=round(luminance,1))

def main():
    path=ROOT/'assets/media/catalog.json'
    catalog=json.loads(path.read_text(encoding='utf8'))
    rules=['/* Generated by tools/photo_grade.py; original images are unchanged. */',
           '.client-photo{filter:brightness(var(--photo-exposure,1.06)) contrast(.95) saturate(var(--photo-saturation,.76)) sepia(.28)}']
    for project in catalog['projects']:
        variant=min(project['variants'],key=lambda v:abs(v['width']-800))
        with Image.open(ROOT/variant['src']) as image:project['grade']=grade_for(image)
        grade=project['grade']
        rules.append(f'.client-photo[src*="assets/media/{project["key"]}-"]{{--photo-exposure:{grade["exposure"]};--photo-saturation:{grade["saturation"]}}}')
    (ROOT/'assets/css/photo-grade.css').write_text('\n'.join(rules)+'\n',encoding='utf8')
    path.write_text(json.dumps(catalog,ensure_ascii=False,indent=2),encoding='utf8')
    print('Measured and graded',len(catalog['projects']),'images; source files unchanged.')

if __name__=='__main__':main()
